CREATE TABLE IF NOT EXISTS users(
  id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
  pw_hash TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'worker', active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS customers(
  id INTEGER PRIMARY KEY, name TEXT NOT NULL, country TEXT NOT NULL DEFAULT 'CZ',
  ico TEXT DEFAULT '', dic TEXT DEFAULT '', email TEXT DEFAULT '', phone TEXT DEFAULT '',
  address TEXT DEFAULT '', note TEXT DEFAULT '');
CREATE TABLE IF NOT EXISTS jobs(
  id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers(id),
  number TEXT NOT NULL, name TEXT NOT NULL, site_address TEXT DEFAULT '',
  status TEXT NOT NULL DEFAULT 'poptavka', currency TEXT NOT NULL DEFAULT 'CZK',
  start_date TEXT, end_plan TEXT, budget REAL NOT NULL DEFAULT 0, note TEXT DEFAULT '');
CREATE TABLE IF NOT EXISTS diary(
  id INTEGER PRIMARY KEY, job_id INTEGER NOT NULL REFERENCES jobs(id), date TEXT NOT NULL,
  weather TEXT DEFAULT '', workers INTEGER DEFAULT 0, hours REAL DEFAULT 0,
  work_done TEXT DEFAULT '', issues TEXT DEFAULT '', user_id INTEGER REFERENCES users(id));
CREATE TABLE IF NOT EXISTS photos(
  id INTEGER PRIMARY KEY, job_id INTEGER NOT NULL REFERENCES jobs(id),
  entry_id INTEGER REFERENCES diary(id), filename TEXT NOT NULL, caption TEXT DEFAULT '',
  phase TEXT DEFAULT 'behem', area TEXT DEFAULT '', taken TEXT, src_hash TEXT);
CREATE TABLE IF NOT EXISTS items(
  id INTEGER PRIMARY KEY, name TEXT NOT NULL, unit TEXT NOT NULL DEFAULT 'ks',
  buy_czk REAL DEFAULT 0, buy_eur REAL DEFAULT 0, sell_czk REAL DEFAULT 0, sell_eur REAL DEFAULT 0);
CREATE TABLE IF NOT EXISTS job_material(
  job_id INTEGER NOT NULL REFERENCES jobs(id), item_id INTEGER NOT NULL REFERENCES items(id),
  plan_qty REAL NOT NULL DEFAULT 0, PRIMARY KEY(job_id,item_id));
CREATE TABLE IF NOT EXISTS material_use(
  id INTEGER PRIMARY KEY, job_id INTEGER NOT NULL REFERENCES jobs(id),
  item_id INTEGER NOT NULL REFERENCES items(id), entry_id INTEGER REFERENCES diary(id),
  date TEXT NOT NULL, qty REAL NOT NULL);
CREATE TABLE IF NOT EXISTS stages(
  id INTEGER PRIMARY KEY, job_id INTEGER NOT NULL REFERENCES jobs(id), name TEXT NOT NULL,
  weight REAL NOT NULL DEFAULT 1, percent REAL NOT NULL DEFAULT 0, plan_from TEXT, plan_to TEXT);
CREATE TABLE IF NOT EXISTS docs(
  id INTEGER PRIMARY KEY, job_id INTEGER NOT NULL REFERENCES jobs(id), kind TEXT NOT NULL,
  number TEXT NOT NULL UNIQUE, issued TEXT NOT NULL, due TEXT, currency TEXT NOT NULL,
  vat_mode TEXT NOT NULL DEFAULT 'cz', status TEXT NOT NULL DEFAULT 'koncept', note TEXT DEFAULT '');
CREATE TABLE IF NOT EXISTS doc_items(
  id INTEGER PRIMARY KEY, doc_id INTEGER NOT NULL REFERENCES docs(id) ON DELETE CASCADE,
  text TEXT NOT NULL, unit TEXT DEFAULT 'ks', qty REAL NOT NULL DEFAULT 1,
  price REAL NOT NULL DEFAULT 0, vat_rate REAL NOT NULL DEFAULT 21);
